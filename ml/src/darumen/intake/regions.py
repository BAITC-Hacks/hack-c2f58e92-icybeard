LATIN_TO_CYRILLIC = str.maketrans(
    {"O": "О", "o": "о", "A": "А", "a": "а", "E": "Е", "e": "е", "C": "С", "c": "с", "P": "Р",
     "p": "р", "H": "Н", "K": "К", "T": "Т", "M": "М", "B": "В", "X": "Х", "y": "у"}
)
STOP_TOKENS = {"область", "обл", "г", "га", "город", "республиканского", "значения"}
_NON_LETTERS = re.compile(r"[^a-zа-яёәғқңөұүһі\s]")
_PARENTHESES = re.compile(r"\([^)]*\)")  # "г. Астана (действовавший до 23.03.2019)"

VARIANTS: dict[str, str] = {v: k for k, vs in _VARIANTS.items() for v in vs}


def normalize_region_text(value: str) -> str:
    text = _PARENTHESES.sub(" ", value).translate(LATIN_TO_CYRILLIC).lower()
    text = _NON_LETTERS.sub(" ", text)
    tokens = [t for t in text.split() if t not in STOP_TOKENS and len(t) > 1]
    return " ".join(tokens)


def to_kato(value: str | None) -> str | None:
    """Two-digit KATO code for a region name or a full KATO code, or None when unknown."""
    if value is None:
        return None
    text = str(value).strip()
    if not text:
        return None
    if text.isdigit():
        code = text[:2]
        return code if code in REGIONS else None
    return VARIANTS.get(normalize_region_text(text))
