"""Model cards for the stream models, rendered from the JSON reports written by training."""
from __future__ import annotations

import json
from pathlib import Path

from ..intake.pipeline import Lakehouse

STREAM_TITLES = {
    "admissions_monthly": "Госпитализации по региону и профилю, месяцы (ЭРСБ, 2012–2026)",
    "er_visits_daily": "Обращения в приёмный покой без госпитализации, дни (ИС БГ, I квартал 2025)",
    "vac_monthly": "Дозы вакцин по региону и плану, месяцы (ИС Вакцинация)",
}


def _reports(lake: Lakehouse, kind: str) -> list[dict]:
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted((lake.root / "models" / kind).glob("*/report.json"))]


def forecast_card(lake: Lakehouse) -> str:
    lines = [
        "# Карточка модели: прогноз нагрузки по потокам",
        "",
        "Один механизм для любого зарегистрированного потока (`streams/*.yaml`): AutoETS с сезонностью потока против",
        "сезонного наива, скользящий бэктест (rolling origin) на последних окнах истории, итоговый прогноз с 80 % интервалом.",
        "Метрика выбора модели: MASE (ошибка относительно сезонного наива на обучающей части ряда), дополнительно sMAPE.",
        "",
        "| Поток | Рядов | Горизонт | Модель | MASE (модель / наив) | sMAPE (модель / наив) | Рядов лучше наива |",
        "|---|---|---|---|---|---|---|",
    ]
    for rep in _reports(lake, "forecast"):
        if rep.get("skipped"):
            continue
        chosen, base = rep["chosen"], rep["baseline"]
        m, b = rep["models"][chosen], rep["models"][base]
        better = m.get("series_better_than_baseline")
        better_text = f"{better:.0%}" if better is not None else "—"
        lines.append(f"| {STREAM_TITLES.get(rep['stream'], rep['stream'])} | {rep['series']:,} | {rep['horizon']} | {chosen} | "
                     f"{m['mase']:.3f} / {b['mase']:.3f} | {m['smape']:.3f} / {b['smape']:.3f} | {better_text} |")
    lines += [
        "", "## Как читать", "",
        "- MASE < 1 означает, что модель точнее сезонного наива на том же ряде; итоговый прогноз строится выбранной моделью.",
        "- Неполный хвост данных (последние месяцы, которые источник ещё догружает) отбрасывается автоматически по доле от медианы года.",
        "- Ряды короче минимальной истории потока не прогнозируются; пропуски заполняются нулями.",
        "", "## Ограничения", "",
        "- Приёмные покои: история только 90 дней, поэтому недельная сезонность выучена, годовая нет.",
        "- Вакцинация: кампании (COVID-19 и сезонный грипп) дают скачки, которые статистические модели не предсказывают; sMAPE высокий.",
        "- Госпитализации: у трети случаев профиль койки не сопоставлен с справочником и учтён как отдельный ряд «unknown».",
    ]
    return "\n".join(lines) + "\n"


def anomaly_card(lake: Lakehouse) -> str:
    lines = [
        "# Карточка модели: детектор аномалий по потокам",
        "",
        "Робастный z-score относительно собственной истории ряда: ожидаемое значение = медиана того же периода сезона",
        "(тот же день недели за 4 недели, тот же месяц за 3 года) с поправкой на тренд, разброс = MAD остатков; масштаб не опускается",
        "ниже пуассоновского уровня √(ожидание) и 15 % уровня. Сигналы делятся на «организация» и «общая волна» по медиане z в группе",
        "похожих (регион для приёмных покоев, профиль или план вакцинации для месячных потоков).",
        "",
        "Проверка: в реальные ряды подсаживаются всплески ×3, затем измеряется, где они оказываются в ранжировании.",
        "",
        "| Поток | Рядов | Сигналов | Критических | По организации | Полнота при пороге | Медианный перцентиль подсаженных | Сигналов на 1000 точек |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for rep in _reports(lake, "anomaly"):
        if rep.get("skipped"):
            continue
        lines.append(f"| {STREAM_TITLES.get(rep['stream'], rep['stream'])} | {rep['series']:,} | {rep['alerts']:,} | {rep['critical']:,} | "
                     f"{rep['entity_specific']:,} | {rep['recall_at_threshold']:.2f} | {rep.get('injected_rank_percentile_median', float('nan')):.2f} | "
                     f"{rep['alerts_per_1000_points']:.1f} |")
    lines += [
        "", "## Как читать", "",
        "- Подсаженные всплески попадают в верхний 1–5 % ранжирования: лента сигналов сортируется по score, и верх списка содержит настоящие отклонения.",
        "- Precision@k против подсаженных всплесков занижена намеренно: в реальных рядах есть собственные крупные отклонения, они и занимают верх списка.",
        "- Ряд, который был неактивен большую часть окна, не оценивается: у него нет базы для сравнения.",
        "", "## Ограничения", "",
        "- Порог один на поток; для вакцинации он поднят до 4.5 из-за кампаний, поток всё равно шумный и предназначен для ранжированного просмотра.",
        "- Сезонность учитывается только через сезонную медиану и мультипликативный тренд; праздники и переносы не моделируются.",
    ]
    return "\n".join(lines) + "\n"


def simulate_card(lake: Lakehouse) -> str | None:
    path = lake.root / "models" / "simulate" / "counterfactual_q1.json"
    if not path.exists():
        return None
    s = json.loads(path.read_text(encoding="utf-8"))
    c = s.get("consistency", {})
    lo, hi = s["saved_days_band"]
    return "\n".join([
        "# Карточка модели: симулятор очереди и перераспределение",
        "",
        f"Версия {s['model'].split('@')[1]}. Жидкостная модель очереди по организации и профилю: очередь L, поток направлений λ и пропускная",
        "способность μ за последние 28 дней; ожидание ≈ k · L / μ, где k калибруется по профилю на фактическом медианном ожидании (M1).",
        "Сценарии: «+мощность» меняет μ, «перенаправить долю» меняет λ. Перераспределение: жадный перенос доли направлений от самой медленной",
        "организации региона к самой быстрой шагами по 5 %, не более 20 % от источника, пока суммарные дни ожидания падают.",
        "",
        "## Контрфактический прогон на I квартале 2025",
        "",
        "| Дата старта | Горизонт | Групп регион×профиль с переносами | Дней ожидания без переносов | Сэкономлено дней | Доля | Интервал (поток ±20 %) |",
        "|---|---|---|---|---|---|---|",
        (f"| {s['as_of']} | {s['horizon_days']} дней | {s['groups_with_moves']} | {s['wait_days_before']:,.0f} | {s['saved_days']:,.0f} | "
        f"{s['saved_share']:.1%} | {lo:,.0f} – {hi:,.0f} дней ({s['saved_share_band'][0]:.1%} – {s['saved_share_band'][1]:.1%}) |"),
        "",
        "## Согласованность с фактом",
        "",
        (f"На {c.get('n', 0):,} парах организация×профиль с фактическим ожиданием за 4 недели: ранговая корреляция Спирмена "
        f"{c.get('spearman', float('nan')):.2f}, MAE {c.get('mae_days', float('nan')):.1f} дня, медиана модели {c.get('median_predicted_days', float('nan')):.1f} "
        f"против факта {c.get('median_observed_days', float('nan')):.1f} дня."),
        "",
        "## Ограничения",
        "",
        "- Модель детерминированная: стохастичность очереди заменена интервалом по потоку направлений ±20 %.",
        "- Перенос доли направлений предполагает, что пациент согласен на другую организацию того же региона и профиля; расстояние и транспорт не учитываются.",
        "- Пропускная способность взята из фактических госпитализаций, а не из коечного фонда; при получении данных о койках μ станет функцией занятости.",
        "- Оптимизация жадная и по одной группе; глобальный оптимизатор назначения (OR-Tools) остаётся расширением.",
    ]) + "\n"


def write_cards(lake: Lakehouse, cards_dir: Path) -> list[Path]:
    cards_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in (("forecast.md", forecast_card(lake)), ("anomaly.md", anomaly_card(lake)), ("simulate.md", simulate_card(lake))):
        if text is None:
            continue
        path = cards_dir / name
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written
