part of 'strings.dart';

/// Подписи о внешних сервисах (`GET /public/service-status`): баннер почты в shell'ах, карточка на экране
/// восстановления пароля, каналы уведомлений, вход через eGov mobile, заметка о push. Честно: чего нет — того нет.
extension ServiceStrings on S {
  // ---------- причины недоступности ----------
  /// Причина из ответа API; неизвестная или пустая — общий текст.
  String serviceReason(ServiceReason? reason) => switch (reason) {
        ServiceReason.smtpNotConfigured => _t('Почтовый сервер не настроен', 'Пошта сервері бапталмаған'),
        ServiceReason.smtpUnreachable => _t('Почтовый сервер не отвечает', 'Пошта сервері жауап бермейді'),
        ServiceReason.notReady => _t('Сервис ещё не подключён', 'Қызмет әлі қосылмаған'),
        ServiceReason.endpointNotProvided => _t('Адрес сервиса не предоставлен', 'Қызмет мекенжайы берілмеген'),
        ServiceReason.other || null => _t('Сервис временно недоступен', 'Қызмет уақытша қолжетімсіз'),
      };

  /// SMS (код входа и канал уведомлений): шлюза нет, функция не построена — та же подпись, что у каналов уведомлений.
  String get smsNotConnected => serviceReason(ServiceReason.notReady);

  /// Подпись канала под названием: работает — null, неизвестно — «не удалось проверить», иначе причина.
  String? serviceState(ServiceAvailability service) => service.isUp
      ? null
      : service.isUnknown
          ? _t('Не удалось проверить работу сервиса', 'Қызметтің жұмысын тексеру мүмкін болмады')
          : serviceReason(service.reason);

  // ---------- баннер почты в shell'ах ----------
  String get emailOutageBanner => _t(
        'Почтовый сервер недоступен. Письма — приглашения, сброс пароля, уведомления — сейчас не отправляются.',
        'Пошта сервері қолжетімсіз. Хаттар — шақырулар, құпия сөзді қалпына келтіру, хабарламалар — қазір жіберілмейді.',
      );
  String get dismissNotice => _t('Скрыть уведомление', 'Хабарламаны жасыру');

  // ---------- восстановление пароля без почты ----------
  String get resetMailDownTitle => _t('Письмо сейчас не придёт', 'Хат қазір келмейді');
  String get resetMailDownBody => _t(
        'Почтовый сервер недоступен, поэтому письмо со ссылкой для смены пароля сейчас не будет отправлено. Обратитесь к администратору своей организации.',
        'Пошта сервері қолжетімсіз, сондықтан құпия сөзді ауыстыру сілтемесі бар хат қазір жіберілмейді. Ұйымыңыздың әкімшісіне хабарласыңыз.',
      );
  String get requestAcceptedTitle => _t('Запрос принят', 'Сұрау қабылданды');
  String mailNotSentBody(String email) =>
      _t('Письмо на $email сейчас не отправится: почтовый сервер недоступен.', '$email мекенжайына хат қазір жіберілмейді: пошта сервері қолжетімсіз.');
  String get askAdminNote =>
      _t('Чтобы сменить пароль, обратитесь к администратору организации.', 'Құпия сөзді ауыстыру үшін ұйым әкімшісіне хабарласыңыз.');

  // ---------- каналы уведомлений ----------
  String get channelsLabel => _t('Каналы доставки', 'Жеткізу арналары');
  String get channelInApp => _t('В приложении', 'Қосымшада');
  String get channelEmail => _t('Почта', 'Пошта');
  String get channelSms => 'SMS';
  String get channelPush => _t('Push-уведомления', 'Push-хабарламалар');
  String get channelWorks => _t('работает', 'жұмыс істейді');
  String get onlyInAppNote => _t('Сейчас доставляются только уведомления в приложении.', 'Қазір тек қосымшадағы хабарламалар жеткізіледі.');
  String get onlyInAppShort => _t('только в приложении', 'тек қосымшада');
  String get storedPrefsKeptNote => _t(
        'Сохранённые настройки почты, SMS и push не сбрасываются — они начнут действовать, когда сервис заработает.',
        'Пошта, SMS және push баптаулары сақталады — қызмет іске қосылғанда қолданыла бастайды.',
      );
  String get perEventInWeb => _t('Настроить по событиям в веб-кабинете', 'Оқиғалар бойынша веб-кабинетте баптау');

  // ---------- push на экране уведомлений ----------
  String pushDownNote(ServiceReason? reason) => reason == ServiceReason.notReady
      ? _t(
          'Push-уведомления пока не приходят: сервис ещё не подключён. Новые события появляются здесь.',
          'Push-хабарламалар әзірге келмейді: қызмет әлі қосылмаған. Жаңа оқиғалар осында пайда болады.',
        )
      : _t('Push-уведомления сейчас не приходят. Новые события появляются здесь.', 'Push-хабарламалар қазір келмейді. Жаңа оқиғалар осында пайда болады.');

  // ---------- вход через eGov mobile ----------
  String get egovUnavailableCaption => _t('Сервис eGov mobile сейчас недоступен', 'eGov mobile қызметі қазір қолжетімсіз');
  String get egovUnavailableTitle => _t('Вход через eGov mobile недоступен', 'eGov mobile арқылы кіру қолжетімсіз');

  /// Почему вход через eGov не работает: адрес Smart Bridge не предоставлен — прямо, остальное — общим текстом.
  String egovUnavailableBody(ServiceReason? reason) => reason == ServiceReason.endpointNotProvided
      ? _t(
          'Адрес сервиса eGov mobile (Smart Bridge) не предоставлен, поэтому вход через eGov сейчас недоступен. Войдите по логину и паролю.',
          'eGov mobile (Smart Bridge) қызметінің мекенжайы берілмеген, сондықтан eGov арқылы кіру қазір қолжетімсіз. Логин мен құпия сөз арқылы кіріңіз.',
        )
      : _t(
          'Сервис eGov mobile сейчас недоступен, поэтому вход через eGov не работает. Войдите по логину и паролю.',
          'eGov mobile қызметі қазір қолжетімсіз, сондықтан eGov арқылы кіру жұмыс істемейді. Логин мен құпия сөз арқылы кіріңіз.',
        );
  String get egovNotInAppTitle => _t('Вход через eGov mobile', 'eGov mobile арқылы кіру');
  String get egovNotInAppBody => _t(
        'Сервис eGov mobile подключён, но вход через него в этой версии приложения ещё не реализован. Войдите по логину и паролю.',
        'eGov mobile қызметі қосылған, бірақ қосымшаның осы нұсқасында ол арқылы кіру әлі іске асырылмаған. Логин мен құпия сөз арқылы кіріңіз.',
      );
}
